-- changeset istad:005-create-user-sessions
CREATE TABLE iam_user_sessions
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             UUID         NOT NULL UNIQUE,
    user_id          BIGINT       NOT NULL,
    session_key      VARCHAR(200) NOT NULL,
    device           VARCHAR(100),
    browser          VARCHAR(100),
    operating_system VARCHAR(100),
    ip_address       VARCHAR(45),
    location         VARCHAR(100),
    user_agent       VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    last_activity_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE,
    revoked_at       TIMESTAMP WITH TIME ZONE,
    revoked_by       VARCHAR(100),
    revoked_reason   VARCHAR(255),
    version          BIGINT       NOT NULL,
    CONSTRAINT fk_iam_session_user FOREIGN KEY (user_id) REFERENCES iam_users (id)
);

CREATE INDEX idx_iam_session_user ON iam_user_sessions (user_id);
CREATE INDEX idx_iam_session_key ON iam_user_sessions (session_key);
CREATE INDEX idx_iam_session_revoked ON iam_user_sessions (revoked_at);

