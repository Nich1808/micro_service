CREATE TABLE iam_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    email_verified BOOLEAN NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    given_name VARCHAR(100) NOT NULL,
    family_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    nickname VARCHAR(100),
    gender VARCHAR(30),
    birthdate DATE,
    profile_url VARCHAR(500),
    picture_url VARCHAR(500),
    website_url VARCHAR(500),
    zoneinfo VARCHAR(100),
    locale VARCHAR(20),
    phone_number VARCHAR(30),
    phone_number_verified BOOLEAN NOT NULL,
    street_address VARCHAR(255),
    locality VARCHAR(100),
    region VARCHAR(100),
    postal_code VARCHAR(30),
    country VARCHAR(100),
    enabled BOOLEAN NOT NULL,
    account_non_expired BOOLEAN NOT NULL,
    account_non_locked BOOLEAN NOT NULL,
    credentials_non_expired BOOLEAN NOT NULL,
    failed_login_attempts INTEGER NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE,
    password_changed_at TIMESTAMP WITH TIME ZONE,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL
);

CREATE TABLE iam_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    system BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL
);

CREATE TABLE iam_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    resource VARCHAR(50) NOT NULL,
    action VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    system BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL
);

CREATE TABLE iam_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    email_verified BOOLEAN NOT NULL,
    display_name VARCHAR(255),
    username VARCHAR(100),
    picture_url VARCHAR(500),
    attributes JSONB,
    linked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT fk_iam_identity_user
        FOREIGN KEY (user_id) REFERENCES iam_users(id),
    CONSTRAINT uk_iam_identity_provider_subject
        UNIQUE (provider, provider_subject)
);

CREATE TABLE iam_user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_by VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_by VARCHAR(100),
    reason VARCHAR(255),
    CONSTRAINT fk_iam_user_role_user
        FOREIGN KEY (user_id) REFERENCES iam_users(id),
    CONSTRAINT fk_iam_user_role_role
        FOREIGN KEY (role_id) REFERENCES iam_roles(id)
);

CREATE TABLE iam_role_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_by VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_by VARCHAR(100),
    reason VARCHAR(255),
    CONSTRAINT fk_iam_role_permission_role
        FOREIGN KEY (role_id) REFERENCES iam_roles(id),
    CONSTRAINT fk_iam_role_permission_permission
        FOREIGN KEY (permission_id) REFERENCES iam_permissions(id)
);

CREATE TABLE iam_user_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    effect VARCHAR(10) NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_by VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_by VARCHAR(100),
    reason VARCHAR(255),
    CONSTRAINT fk_iam_user_permission_user
        FOREIGN KEY (user_id) REFERENCES iam_users(id),
    CONSTRAINT fk_iam_user_permission_permission
        FOREIGN KEY (permission_id) REFERENCES iam_permissions(id)
);
